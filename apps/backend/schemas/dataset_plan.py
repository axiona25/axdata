"""DatasetPlan schema for OpenAI tool calling."""
from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional
from enum import Enum


class Domain(str, Enum):
    """Dataset domain."""
    ECONOMICS = "economics"
    BIOMEDICAL = "biomedical"
    PHYSICS = "physics"
    MATH = "math"
    DEMOGRAPHY = "demography"


class SourcePlan(BaseModel):
    """Source plan for data collection."""
    connector: str = Field(..., description="Connector name (e.g., 'worldbank', 'eurostat', 'pubmed')")
    queries: List[Dict[str, Any]] = Field(..., description="List of queries for this connector")


class TransformationPlan(BaseModel):
    """Transformation plan."""
    type: str = Field(..., description="Transformation type (e.g., 'normalize_dates', 'join', 'dedup')")
    params: Optional[Dict[str, Any]] = Field(None, description="Transformation parameters")


class DatasetPlan(BaseModel):
    """Dataset plan generated by OpenAI - FAIR-compliant."""
    domain: Domain = Field(..., description="Dataset domain")
    title: str = Field(..., min_length=1, max_length=255, description="Dataset title")
    sources: List[SourcePlan] = Field(..., min_items=1, description="Data sources")
    transformations: Optional[List[TransformationPlan]] = Field(default=[], description="Data transformations")
    outputs: List[str] = Field(
        default=["csv", "json", "parquet"],
        description="Output formats"
    )
    documentation: Dict[str, bool] = Field(
        default={"include_manifest": True, "include_data_dictionary": True},
        description="Documentation options"
    )
    # FAIR-compliant metadata fields
    methodology: Optional[str] = Field(None, description="Methodology description")
    license: Optional[str] = Field(None, description="License information")
    citation: Optional[str] = Field(None, description="Citation string")
    geographic_coverage: Optional[str] = Field(None, description="Geographic coverage")
    temporal_coverage: Optional[str] = Field(None, description="Temporal coverage")
    version: Optional[str] = Field("1.0", description="Dataset version")
    indicators_metadata: Optional[Dict[str, Dict[str, Any]]] = Field(
        None,
        description="Metadata for indicators/columns (description, unit, notes)"
    )


